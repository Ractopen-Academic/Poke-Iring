  static TieredAchievement _createTrack({
    required String id,
    required String title,
    required String description,
    required AchievementCategory category,
    required String unit,
    required List<double> targets,
    required List<int> points,
    ExplorerTitle? bronzeTitle,
    ExplorerTitle? silverTitle,
    ExplorerTitle? goldTitle,
    ExplorerTitle? platTitle,
  }) {
    final milestones = [
      AchievementMilestone(
        tier: AchievementTier.bronze,
        targetValue: targets[0],
        rewardPawPoints: points[0],
        rewardTitle: bronzeTitle,
      ),
      AchievementMilestone(
        tier: AchievementTier.silver,
        targetValue: targets[1],
        rewardPawPoints: points[1],
        rewardTitle: silverTitle,
      ),
      AchievementMilestone(
        tier: AchievementTier.gold,
        targetValue: targets[2],
        rewardPawPoints: points[2],
        rewardTitle: goldTitle,
      ),
      AchievementMilestone(
        tier: AchievementTier.platinum,
        targetValue: targets[3],
        rewardPawPoints: points[3],
        rewardTitle: platTitle,
      ),
    ];

    return TieredAchievement(
      id: id,
      title: title,
      description: description,
      category: category,
      unit: unit,
      milestones: milestones,
    );
  }
